// Drives the Add app wizard end to end. bun scripts/e2e-add.ts <outDir>
import { chromium } from 'playwright-core';
const out = process.argv[2];
const TAB = process.env.TAB || 'store';
const SRC = process.env.SRC || 'https://f-droid.org/packages/de.markusfisch.android.binaryeye/';
const CUSTOM = process.env.CUSTOM !== '0';
const P = process.env.PREFIX || '';
const U = 'https://relevance.cocoparrot-backend.workers.dev';
const browser = await chromium.launch({ executablePath: process.env.CHROME, args: ['--no-sandbox'] });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 950 } })).newPage();
page.on('pageerror', (e) => console.log('pageerror', e.message));
page.on('console', (m) => m.type() === 'error' && console.log('console', m.text()));
await page.goto(U + '/api/config');
await page.evaluate((t) => localStorage.setItem('rv-token', t), process.env.TOKEN!);
const snap = async (n: string) => { await page.waitForTimeout(900); await page.screenshot({ path: `${out}/${P}${n}.png`, fullPage: true }); console.log('shot', n); };
await page.goto(U + '/dashboard', { waitUntil: 'networkidle' });
await page.waitForTimeout(4000);
await snap('01-dashboard');
await page.goto(U + '/add', { waitUntil: 'networkidle' });
await page.waitForTimeout(1500);
if (TAB === 'github') await page.click('.tabchip:has-text("GitHub Releases")');
await page.fill('input.input.mono', SRC);
await page.click('button.fetch');
await page.waitForSelector('.found', { timeout: 30000 });
await snap('02-source');
await page.click('.nav .btn.lg');
await page.waitForSelector('.tools');
await page.waitForTimeout(2500);
await snap('03-tool');
await page.click('.tool:has-text("No patching")');
await page.click('.nav .btn.lg');
await page.waitForSelector('.ids');
if (CUSTOM) {
await page.fill('.ids input.input >> nth=0', 'Binary Eye Mod');
await page.click('button:has-text("Suggest")');
await page.check('.toggle input');
await page.waitForTimeout(1200);
await page.click('.pre:has-text("RV")');
await page.locator('.slider.hue input').fill('40');
}
await snap('04-customize');
await page.click('.nav .btn.lg');
await page.waitForSelector('.form');
await snap('05-listing');
await page.click('.nav .btn.lg');
await page.waitForSelector('.plan');
await snap('06-review');
await page.click('.nav .btn.lg');
await page.waitForURL(/\/builds\/\d+/, { timeout: 90000 });
await page.waitForTimeout(+(process.env.WAIT || 25000));
await snap('07-build');
console.log('url', page.url());
await browser.close();
